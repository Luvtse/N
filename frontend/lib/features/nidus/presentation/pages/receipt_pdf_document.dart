/// §3.4 — client-side receipt PDF generated from the ride DTO (plan: "The
/// PDF is generated client-side from the DTO"). No server round-trip, no
/// fabricated numbers: every line renders only what the backend actually
/// sent. When [Ride.fareBreakdown] is absent (legacy rides), the document
/// prints the total with an explicit "itemization unavailable for this
/// ride" note instead of inventing components.
library;

/// Builds and saves the receipt PDF into the app's documents directory.
/// Returns the saved file so callers can share it. Throws on I/O failure —
/// call sites must surface an honest error state, never a fake success toast.
Future<File> saveReceiptPdf(Ride ride) async {
  final doc = buildReceiptDocument(ride);
  final bytes = await doc.save();
  final dir = await getApplicationDocumentsDirectory();
  final file = File('${dir.path}/nidus-receipt-${ride.id}.pdf');
  await file.writeAsBytes(bytes, flush: true);
  return file;
}

/// Pure builder so the document can be unit-tested without touching disk.
pw.Document buildReceiptDocument(Ride ride) {
  final doc = pw.Document(title: 'Nidus Receipt ${ride.id}');
  final money = NumberFormat.currency(
    locale: 'en',
    symbol: '${ride.currency} ',
    decimalDigits: 2,
  );
  final df = DateFormat('yyyy-MM-dd HH:mm');

  final breakdown = ride.fareBreakdown;
  final lines = <(String, double)>[];
  if (breakdown != null) {
    void add(String label, double? v) {
      if (v != null && v != 0) lines.add((label, v));
    }

    add('Base fare', breakdown.base);
    add('Distance', breakdown.distance);
    add('Time', breakdown.time);
    add('Surge', breakdown.surge);
    add('Service fee', breakdown.serviceFee);
    add('Promo discount', breakdown.promoDiscount == null
        ? null
        : -breakdown.promoDiscount!);
    add('Tip', breakdown.tip);
  }

  doc.addPage(
    pw.Page(
      pageFormat: PdfPageFormat.a4,
      build: (_) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text('Nidus Ride Receipt',
              style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold)),
          pw.SizedBox(height: 4),
          pw.Text('Ride ${ride.id}', style: const pw.TextStyle(fontSize: 11)),
          pw.Divider(),
          _row('Status', ride.status.replaceAll('_', ' ')),
          if (ride.requestedAt != null) _row('Requested', df.format(ride.requestedAt!)),
          if (ride.completedAt != null) _row('Completed', df.format(ride.completedAt!)),
          if (ride.driver != null) ...[
            _row('Driver', ride.driver!.name),
            _row('Vehicle', '${ride.driver!.vehicleType} · ${ride.driver!.vehiclePlate}'),
          ],
          pw.SizedBox(height: 8),
          _row('Pickup', ride.pickupAddress ?? '(address unavailable)'),
          _row('Dropoff', ride.dropoffAddress ?? '(address unavailable)'),
          if (ride.distanceKm != null) _row('Distance', '${ride.distanceKm!.toStringAsFixed(2)} km'),
          if (ride.durationMinutes != null) _row('Duration', '${ride.durationMinutes} min'),
          pw.Divider(),
          if (lines.isNotEmpty) ...[
            for (final (label, value) in lines)
              _row(label, money.format(value), alignRight: true),
            pw.Divider(),
            _row(
              'Total',
              money.format(ride.fareAmount ?? 0),
              bold: true,
              alignRight: true,
            ),
          ] else ...[
            pw.Text(
              'Itemization unavailable for this ride.',
              style: pw.TextStyle(
                fontSize: 11,
                color: PdfColors.amber800,
                fontStyle: pw.FontStyle.italic,
              ),
            ),
            pw.SizedBox(height: 6),
            _row(
              'Total',
              money.format(ride.fareAmount ?? 0),
              bold: true,
              alignRight: true,
            ),
          ],
          if (ride.paymentMethodType != null)
            _row('Payment method', ride.paymentMethodType!),
          if (ride.cashCollectedAt != null)
            _row('Cash collected by driver', df.format(ride.cashCollectedAt!))
          else if (ride.pendingCashCollection == true)
            _row('Cash collection', 'Pending driver confirmation'),
          pw.Spacer(),
          pw.Text('Generated by Nidus on ${df.format(DateTime.now())}',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
        ],
      ),
    ),
  );
  return doc;
}

pw.Widget _row(String label, String value,
        {bool bold = false, bool alignRight = false}) =>
    pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 2),
      child: pw.Row(
        mainAxisAlignment: alignRight
            ? pw.MainAxisAlignment.spaceBetween
            : pw.MainAxisAlignment.start,
        children: [
          pw.Text('$label:  ',
              style: pw.TextStyle(
                  fontSize: 11,
                  fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
                  color: PdfColors.grey700)),
          pw.Expanded(
            child: pw.Text(
              value,
              textAlign: alignRight ? pw.TextAlign.right : pw.TextAlign.left,
              style: pw.TextStyle(
                  fontSize: 11,
                  fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal),
            ),
          ),
        ],
      ),
    );
